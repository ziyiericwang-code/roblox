// Estimate for countries not in the table, from population and GDP ($M) and income group.
export function estimateMilitary(pop, gdpMd, income) {
  const rich = /^1|^2/.test(income || '');
  const mid = /^3/.test(income || '');
  const active = Math.max(1, Math.min(300, (pop / 1e6) * (rich ? 1.6 : mid ? 1.9 : 1.4)));
  const budget = Math.max(0.05, (gdpMd / 1000) * 0.016);
  const tech = rich ? 4 : mid ? 2 : 1;
  const w = active / 30;
  return {
    active: Math.round(active), reserve: Math.round(active * 0.5), tanks: Math.round(40 * w * (tech / 2)), afv: Math.round(200 * w), artillery: Math.round(60 * w),
    fighters: Math.round(Math.min(60, budget * 4)), cas: Math.round(Math.min(20, budget * 2)), bombers: 0, transport: Math.round(Math.min(20, budget * 2)),
    carriers: 0, destroyers: 0, frigates: Math.round(Math.min(4, budget / 2)), subs: 0, budget, tech,
  };
}
